-- Portaria :: usuários do sistema
--
-- Até aqui o login era um usuário fixo em memória. Isso basta para provar o
-- fluxo de check-in, mas impede qualquer operação sobre a própria conta:
-- não se altera a senha de quem não está persistido, nem se recupera o acesso
-- de quem não tem e-mail guardado.
--
-- SQL padrão, como as demais migrações: a mesma roda no H2 e no PostgreSQL.

CREATE TABLE usuario (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    email      VARCHAR(150) NOT NULL,
    -- O hash BCrypt ocupa 60 caracteres; a folga acomoda algoritmos futuros.
    senha_hash VARCHAR(100) NOT NULL,
    papel      VARCHAR(30)  NOT NULL,
    ativo      BOOLEAN      NOT NULL,
    criado_em  TIMESTAMP    NOT NULL,
    -- O e-mail é o identificador de login. Guardamos sempre em minúsculas
    -- (normalizado na entidade), o que torna esta restrição suficiente para
    -- garantir unicidade sem depender de índice funcional do banco.
    CONSTRAINT uk_usuario_email UNIQUE (email)
);
