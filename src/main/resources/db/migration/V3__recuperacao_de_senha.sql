-- Portaria :: tokens de recuperação de senha
--
-- Guardamos o HASH do token, nunca o token em si. O valor que viaja no link
-- enviado por e-mail existe uma única vez, na memória do servidor, no instante
-- em que é gerado. Se este banco vazar, os tokens não servem para nada --
-- pelo mesmo motivo que não guardamos senhas em texto puro.

CREATE TABLE token_recuperacao_senha (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL,
    -- SHA-256 em hexadecimal: 64 caracteres, tamanho fixo.
    token_hash VARCHAR(64) NOT NULL,
    criado_em  TIMESTAMP   NOT NULL,
    expira_em  TIMESTAMP   NOT NULL,
    -- Nulo enquanto não usado. Preenchido no momento do uso, o que torna
    -- o token de uso único sem precisar apagar a linha -- e deixa rastro
    -- de quando o acesso foi de fato recuperado.
    usado_em   TIMESTAMP,
    CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT uk_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_token_usuario ON token_recuperacao_senha (usuario_id);
