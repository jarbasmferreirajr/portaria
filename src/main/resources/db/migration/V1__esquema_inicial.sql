-- Portaria :: esquema inicial
--
-- SQL propositalmente padrão, sem tipos proprietários, para que a mesma
-- migração rode no H2 hoje e no PostgreSQL depois, sem reescrita.

CREATE TABLE evento (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(150) NOT NULL,
    descricao             VARCHAR(1000),
    local_evento          VARCHAR(200) NOT NULL,
    inicio                TIMESTAMP    NOT NULL,
    fim                   TIMESTAMP,
    capacidade            INTEGER      NOT NULL,
    identificador_publico VARCHAR(80)  NOT NULL,
    criado_em             TIMESTAMP    NOT NULL,
    CONSTRAINT uk_evento_identificador UNIQUE (identificador_publico),
    CONSTRAINT ck_evento_capacidade CHECK (capacidade > 0)
);

CREATE TABLE inscricao (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id   BIGINT       NOT NULL,
    nome        VARCHAR(150) NOT NULL,
    email       VARCHAR(150) NOT NULL,
    telefone    VARCHAR(30),
    motoclube   VARCHAR(120),
    cidade      VARCHAR(120),
    codigo      VARCHAR(6)   NOT NULL,
    criado_em   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_inscricao_evento FOREIGN KEY (evento_id) REFERENCES evento (id),
    -- Código único em todo o sistema: o operador digita apenas o código,
    -- sem precisar escolher o evento antes.
    CONSTRAINT uk_inscricao_codigo UNIQUE (codigo),
    -- Impede inscrição duplicada da mesma pessoa no mesmo evento.
    CONSTRAINT uk_inscricao_evento_email UNIQUE (evento_id, email)
);

CREATE TABLE check_in (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscricao_id   BIGINT      NOT NULL,
    registrado_em  TIMESTAMP   NOT NULL,
    registrado_por VARCHAR(80) NOT NULL,
    CONSTRAINT fk_checkin_inscricao FOREIGN KEY (inscricao_id) REFERENCES inscricao (id),
    -- IDEMPOTÊNCIA GARANTIDA NO BANCO: uma inscrição só pode ter um check-in.
    -- Mesmo com dois operadores escaneando o mesmo código ao mesmo tempo, em
    -- portões diferentes, a segunda gravação falha na restrição em vez de
    -- duplicar a presença e inflar a contagem de público.
    CONSTRAINT uk_checkin_inscricao UNIQUE (inscricao_id)
);

CREATE INDEX ix_inscricao_evento ON inscricao (evento_id);
