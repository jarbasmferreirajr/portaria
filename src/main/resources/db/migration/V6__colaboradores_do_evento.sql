-- Portaria :: colaboradores do evento
--
-- Quem trabalha no dia do evento -- portaria, entrega de kit -- tem CONTA
-- PRÓPRIA, e não um login compartilhado. O motivo está no banco: a tabela
-- check_in guarda registrado_por. Com login emprestado, essa coluna passa a
-- mentir, e junto com ela qualquer resposta à pergunta "quem liberou a entrada
-- dessa pessoa?".
--
-- O vínculo é POR EVENTO, não global: alguém que ajudou no encontro de março
-- não deve continuar com acesso ao de setembro.

CREATE TABLE colaborador_evento (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id  BIGINT      NOT NULL,
    usuario_id BIGINT      NOT NULL,
    -- O que a pessoa faz no evento: portaria, entrega de kit, apoio.
    -- Texto livre: cada organização nomeia suas funções do seu jeito.
    funcao     VARCHAR(60),
    criado_em  TIMESTAMP   NOT NULL,
    CONSTRAINT fk_colaborador_evento  FOREIGN KEY (evento_id)  REFERENCES evento (id),
    CONSTRAINT fk_colaborador_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    -- A mesma pessoa não entra duas vezes no mesmo evento.
    CONSTRAINT uk_colaborador_evento_usuario UNIQUE (evento_id, usuario_id)
);

CREATE INDEX ix_colaborador_evento  ON colaborador_evento (evento_id);
CREATE INDEX ix_colaborador_usuario ON colaborador_evento (usuario_id);
